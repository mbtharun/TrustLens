function describeScore(score) {
  // Descriptive bands only: these are not validated classification thresholds.
  if (score < 0.33) {
    return {
      label: 'Low AI-associated signal',
      direction: 'Leans toward real-photo-like patterns',
      explanation: 'The model found relatively few patterns it associates with AI-generated images. That leans toward the real-photo side of this model’s ranking, but it does not prove the image is genuine.',
      tone: 'low',
    }
  }
  if (score > 0.67) {
    return {
      label: 'Elevated AI-associated signal',
      direction: 'Leans toward AI-generated patterns',
      explanation: 'The model found more patterns it associates with AI-generated images. This is a reason to examine the image’s source more closely, not proof that it was generated by AI.',
      tone: 'high',
    }
  }
  return {
    label: 'Mixed / uncertain signal',
    direction: 'No clear direction from this score',
    explanation: 'The score sits in the middle of the model’s ranking range. This result does not provide a clear indication either way.',
    tone: 'mixed',
  }
}

export default function AnalysisSummary({ result }) {
  const score = result.probability_ai
  const percentage = score * 100
  const reading = describeScore(score)

  return (
    <section className="summary-card">
      <p className="eyebrow">02 / MODEL ASSESSMENT</p>
      <h2 className="serif-heading">What does the model see?</h2>
      <div className={`interpretation-label interpretation-${reading.tone}`}>
        <strong>{reading.label}</strong>
        <span>{reading.direction}</span>
      </div>
      <p className="summary-copy">{reading.explanation}</p>
      <div className="score-heading">
        <span>Model ranking score</span>
        <strong>{score.toFixed(3)} <small>/ 1.000</small></strong>
      </div>
      <div className="score-track" role="img" aria-label={`Model ranking score ${score.toFixed(3)} out of 1`}>
        <span style={{ width: `${percentage}%` }} />
      </div>
      <div className="scale-labels"><span>Lower AI-associated signal</span><span>Higher AI-associated signal</span></div>
      <p className="score-note">{result.note}</p>
      <p className="model-name">MODEL · {result.model}</p>
      <p className="band-caveat">Plain-language ranges are descriptive only, not validated decision thresholds.</p>
    </section>
  )
}